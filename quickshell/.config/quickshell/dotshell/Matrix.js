var cache = {};

// One font's glyphs as arrays of rows of booleans, built once.
function font(name) {
    if (cache[name])
        return cache[name];
    const f = fonts[name] || fonts["5x7"];
    const g = {};
    for (const k in f.g)
        g[k] = f.g[k].split(",").map(r => r.split("").map(c => c === "1"));
    cache[name] = { w: f.w, h: f.h, g: g };
    return cache[name];
}

// What the font can draw: capitals, accents dropped (É -> E). Characters it
// has no glyph for come back as null, so the caller can fall back.
function fold(text) {
    return String(text ?? "").normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase();
}

function covers(name, text) {
    const f = font(name);
    for (const ch of fold(text))
        if (!f.g[ch])
            return false;
    return true;
}
